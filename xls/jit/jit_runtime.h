#ifndef XLS_JIT_JIT_RUNTIME_H_
#define XLS_JIT_JIT_RUNTIME_H_

#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>

#include "absl/container/flat_hash_map.h"
#include "absl/status/status.h"
#include "absl/types/span.h"
#include "llvm/include/llvm/IR/DataLayout.h"
#include "xls/ir/type.h"
#include "xls/ir/value.h"
#include "xls/jit/type_buffer_metadata.h"

namespace xls {

// JitRuntime contains routines necessary for executing code generated by the
// IR JIT. For type resolution, the JIT packs input data into and pulls
// data out of a flat character buffer, thus these routines are necessary.
//
// Thread-safe: all methods read only immutable target layout metadata computed
// at construction time and require no synchronization.
class JitRuntime {
 public:
  explicit JitRuntime(llvm::DataLayout data_layout);

  // Packs the specified values into a flat buffer with the data layout
  // expected by LLVM.
  // "arg_buffers" must contain an entry corresponding to each element in
  // "args", with a matching amount of space allocated.
  absl::Status PackArgs(absl::Span<const Value> args,
                        absl::Span<Type* const> arg_types,
                        absl::Span<uint8_t* const> arg_buffers) const;

  // Returns a Value constructed from the data inside "buffer" whose
  // contents are laid out according to the LLVM interpretation of the passed-in
  // type.
  Value UnpackBuffer(const uint8_t* buffer, const Type* result_type) const;

  // Splats the value into the buffer according to the data layout expected by
  // LLVM.
  void BlitValueToBuffer(const Value& value, const Type* type,
                         absl::Span<uint8_t> buffer) const;

  // Returns the number of bytes that should be allocated for a native LLVM
  // value storing `size` bytes with `alignment` alignment.
  //
  // Note: A user cannot just allocate `size` bytes in every scenario, as there
  //       may be alignment constraints. This method tells us how much to
  //       overallocate.
  size_t ShouldAllocateForAlignment(size_t size, int64_t alignment) const {
    return size + alignment - 1;
  }

  // Returns the number of bytes that should be allocated for a native LLVM
  // stack storing `size` bytes.
  //
  // Note: A user cannot just allocate `size` bytes in every scenario, as there
  //       may be stack alignment constraints. This method tells us how much to
  //       overallocate.
  size_t ShouldAllocateForStack(size_t size) const {
    return ShouldAllocateForAlignment(
        size, data_layout_.getStackAlignment().valueOrOne().value());
  }

  // Converts the provided buffer into a native LLVM buffer by aligning to the
  // given alignment.
  //
  // May reduce the size of the buffer; if the buffer was allocated to hold at
  // least `ShouldAllocateForAlignment(size, alignment)` bytes, then the result
  // is guaranteed to hold at least `size` bytes.
  absl::Span<uint8_t> AsAligned(absl::Span<uint8_t> buffer,
                                int64_t alignment) const;

  // Converts the provided buffer into a native LLVM stack by aligning to the
  // memory model's requirements.
  //
  // May reduce the size of the buffer; if the buffer was allocated to hold at
  // least `ShouldAllocateForStack(size)` bytes, then the result is guaranteed
  // to hold at least `size` bytes.
  absl::Span<uint8_t> AsStack(absl::Span<uint8_t> buffer) const {
    return AsAligned(buffer,
                     data_layout_.getStackAlignment().valueOrOne().value());
  }

  int64_t GetTypeByteSize(const Type* xls_type) const;

  int64_t GetTypeAlignment(const Type* xls_type) const;

  int64_t GetTypeAbiAlignment(const Type* xls_type) const;

  TypeBufferMetadata GetTypeBufferMetadata(const Type* xls_type) const;

  const llvm::DataLayout& data_layout() const { return data_layout_; }

 private:
  // LLVM IntegerType::MAX_INT_BITS is (1 << 23). All XLS Bits types in LLVM
  // layout are rounded up to a power-of-two bit width in [8, 1 << 23].
  static constexpr int kMaxLog2Bits = 23;

  // Immutable target ABI/preferred alignment and endianness parameters
  // extracted once from `llvm::DataLayout`. Querying composite layouts directly
  // on `llvm::DataLayout` (e.g. `getStructLayout`) mutates its internal
  // `LayoutMap`, which previously forced `JitRuntime` to guard all layout and
  // buffer-packing queries with an `absl::Mutex`. Precomputing these scalar
  // target rules lets `ComputeTypeMetricsImpl` evaluate arbitrary XLS bit,
  // array, token, and tuple layouts purely arithmetically with no locks.
  struct TargetLayoutInfo {
    int64_t struct_abi_alignment = 0;
    int64_t struct_pref_alignment = 0;
    int64_t token_abi_alignment = 0;
    int64_t token_pref_alignment = 0;
    // Indexed by `log2_bits` in `[3, kMaxLog2Bits]` (`i8`..`i8388608`);
    // indices `0..2` are unused and remain `0`.
    std::array<int64_t, kMaxLog2Bits + 1> int_abi_alignments{};
    std::array<int64_t, kMaxLog2Bits + 1> int_pref_alignments{};
    bool is_little_endian = false;
  };

  struct TypeMetrics {
    int64_t size;
    int64_t abi_align;
    int64_t pref_align;
  };

  // Optional demand-populated cache mapping composite `Type*` nodes
  // (`TupleType` and `ArrayType`) to their `TypeMetrics` within a single
  // `JitRuntime` call.
  //
  // Starts as `std::nullopt` so flat `Bits`/`Token` types and single-level
  // tuples or arrays of scalars avoid allocating a hash map; engaged lazily via
  // `MaybeInitCompositeChildMemo` only when traversing into a composite child.
  // `BlitValueImpl` and `UnpackBufferImpl` require `memo != nullptr` but do not
  // rely on `*memo` being pre-populated for correctness
  // (`ComputeTypeMetricsImpl` computes and caches any missing composite entry
  // on miss). Passing the `memo` from a preceding sizing call reuses composite
  // subtype metrics already computed during sizing (`O(|type DAG|)`).
  using TypeMetricsMemo =
      std::optional<absl::flat_hash_map<const Type*, TypeMetrics>>;

  static void MaybeInitCompositeChildMemo(const Type* child_type,
                                          TypeMetricsMemo* memo);

  static TargetLayoutInfo GetOrComputeTargetLayoutInfo(
      const llvm::DataLayout& data_layout);

  TypeMetrics GetBitsTypeMetrics(int64_t bit_count) const;
  TypeMetrics ComputeTypeMetrics(const Type* xls_type) const;
  TypeMetrics ComputeTypeMetricsImpl(const Type* xls_type,
                                     TypeMetricsMemo* memo) const;

  Value UnpackBufferImpl(const uint8_t* buffer, const Type* result_type,
                         TypeMetricsMemo* memo) const;
  void BlitValueImpl(const Value& value, const Type* type, uint8_t* buffer,
                     TypeMetricsMemo* memo) const;

  const llvm::DataLayout data_layout_;
  const TargetLayoutInfo layout_info_;
};

}  // namespace xls

#endif  // XLS_JIT_JIT_RUNTIME_H_
